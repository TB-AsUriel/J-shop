function icono(nombre, clase = "") {
  const contenido = ICONOS[nombre];
  if (!contenido) return "";
  return `<svg class="icono${clase ? " " + clase : ""}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${contenido}</svg>`;
}

function hidratarIconos(raiz = document) {
  raiz.querySelectorAll("[data-icono]").forEach(el => {
    el.innerHTML = icono(el.dataset.icono);
  });
}

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", () => hidratarIconos());
} else {
  hidratarIconos();
}
